//! 保存确认对话框动作
//!
//! 关闭工程 / 打开另一个工程 / 退出软件时，若当前工程存在未保存的更改，
//! 弹出此对话框让用户决定：保存当前工程、放弃更改直接关闭、或取消关闭操作。

/// 保存确认对话框动作
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum SaveConfirmAction {
    /// 保存当前工程后继续（关闭/打开/退出）
    Save,
    /// 放弃未保存的更改，直接关闭（不保存）
    Discard,
    /// 取消关闭操作，继续编辑
    Cancel,
}
