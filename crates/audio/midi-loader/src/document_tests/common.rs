//! Document 测试共享工具

/// 创建一个简单的单轨 MIDI 字节序列（含一个 C4 音符）
pub fn create_simple_midi_bytes() -> Vec<u8> {
    let header = [
        0x4D, 0x54, 0x68, 0x64, 0x00, 0x00, 0x00, 0x06, 0x00, 0x00, 0x00, 0x01, 0x01, 0xE0,
    ];
    let track_data = [
        0x4D, 0x54, 0x72, 0x6B, 0x00, 0x00, 0x00, 0x0D, 0x00, 0x90, 0x3C, 0x64, 0x83, 0x60, 0x80,
        0x3C, 0x00, 0x00, 0xFF, 0x2F, 0x00,
    ];
    let mut midi = Vec::with_capacity(header.len() + track_data.len());
    midi.extend_from_slice(&header);
    midi.extend_from_slice(&track_data);
    midi
}
